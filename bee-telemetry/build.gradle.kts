import org.jetbrains.kotlin.gradle.ExperimentalWasmDsl

// What every bee process records about itself: events, spans and its own log lines, kept in
// kuilt-otel's offline-first buffer under the process's data dir. Common code, so the page can
// record the same way once it does (bee telemetry goal 3).
plugins {
    alias(libs.plugins.kotlinMultiplatform)
}

// The commit this build is from, stamped on every record as `bee.commit`. "unknown" outside a git
// checkout (an unzipped source tree), so the build never fails for want of git history.
val commit: Provider<String> = providers.exec {
    commandLine("git", "rev-parse", "--short=12", "HEAD")
    isIgnoreExitValue = true
}.standardOutput.asText.map { it.trim().ifEmpty { "unknown" } }

val writeBuildInfo by tasks.registering {
    description = "Writes BuildInfo.kt, which names the commit this build is from."
    val out = layout.buildDirectory.dir("generated/buildInfo/commonMain/kotlin")
    val stamped = commit
    inputs.property("commit", stamped)
    outputs.dir(out)
    doLast {
        val file = out.get().file("us/tractat/bee/telemetry/BuildInfo.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |package us.tractat.bee.telemetry
            |
            |/** Which build this is, stamped on every record. Generated by bee-telemetry's `writeBuildInfo`. */
            |object BuildInfo {
            |    /** The short commit hash this build is from, or `unknown`. A `val`, so a new commit recompiles only this module. */
            |    val commit: String = "${stamped.get()}"
            |}
            |
            """.trimMargin(),
        )
    }
}

kotlin {
    jvmToolchain(25)
    jvm()
    @OptIn(ExperimentalWasmDsl::class)
    wasmJs { nodejs() }

    sourceSets {
        commonMain {
            kotlin.srcDir(writeBuildInfo)
            dependencies {
                api(project.dependencies.platform(libs.kuilt.bom))
                // Ktor's own BOM, so kuilt-otel-otlp's Ktor matches the version bee pins.
                implementation(project.dependencies.platform(libs.ktor.bom))
                api(libs.kuilt.otel)
                api(libs.kuilt.store)
                // api: RecordingTelemetry.captured takes its NormalizedLogEvent.
                api(libs.kuilt.otel.logging)
                implementation(libs.kotlinx.coroutines.core)
                implementation(libs.kotlin.logging)
            }
        }
        jvmMain.dependencies {
            // The edge that captures every line logback writes ([LogbackEdge]).
            implementation(libs.logback)
            // BEE_OTLP_ENDPOINT's export (OtlpExport): kuilt's OTLP/HTTP edge, over Ktor's CIO client.
            implementation(libs.kuilt.otel.otlp)
            implementation(libs.ktor.client.cio)
            // The reader's --json lines (TimelineMain).
            implementation(libs.kotlinx.serialization.json)
        }
        jvmTest.dependencies {
            // OtlpExportTest's collector: a real OTLP/HTTP endpoint on loopback.
            implementation(libs.ktor.server.netty)
        }
        commonTest.dependencies {
            implementation(kotlin("test"))
            implementation(libs.kuilt.test)
            implementation(libs.kotlinx.coroutines.test)
        }
    }
}
